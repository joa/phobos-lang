// `python/phobos/lang.pyi`, the Python package's view of what the language
// has: the attributes, the scalar types, the built-ins and the standard
// library, each a name `phobos.lang` answers. Generated from the compiler's
// own lists, so a built-in or a library function added here is spelled in
// Python with no other change; a test fails while the committed file lags.

use std::fmt::Write as _;

/// Where the stubs live, from the workspace root.
pub const PATH: &str = "python/phobos/lang.pyi";

const HEADER: &str = r#""""What `phobos.lang` holds, for an editor: every name a kernel body may
spell. Generated by `cargo run -p phobos-lang --features trace --example
site -- stubs`; do not edit."""

from typing import Any, Callable, Sequence, TypeVar

_F = TypeVar("_F")


class Marker:
    """A type, a declaration or `ctx`: read from the source, never run."""

    def __getitem__(self, item: Any) -> "Marker": ...


let: Marker
var: Marker
tensor: Marker
tile: Marker


class _Axes:
    x: int
    y: int
    z: int


class _Ctx:
    block: _Axes
    blocks: _Axes
    threads: int
    warps: int
    lanes: int
    thread: int
    warp: int
    lane: int


ctx: _Ctx


def kernel(fn: Any = None, *, key: Sequence[str] | None = None, reference: Callable[..., Any] | None = None) -> Any:
    """A Phobos kernel, launched as `kernel[grid](*args)`; `key` and
    `reference` are the autotuner's, see `phobos.autotune`."""


def fn(f: Any = None, *, uses: Sequence[str] = ()) -> Any:
    """A Phobos `fn`, inlined at every call; `uses` names what its body
    reads from where it is called."""


def unroll(n: int, loop: range) -> range:
    """`for i in ph.unroll(n, range(lo, hi))` is `for<unroll n> i in range(lo, hi)`."""
"#;

/// The stubs for the compiler as built.
pub fn python() -> String {
    let mut out = HEADER.to_string();

    out.push_str("\n\n# Scalar types, each also a conversion.\n\n");
    for s in crate::ast::Scalar::NAMES {
        let _ = writeln!(out, "{s}: Marker");
    }

    out.push_str("\n\n# Attributes: `@ph.name` or `@ph.name(...)`, read from the source.\n");
    for a in crate::ast::ATTRIBUTES {
        let _ = write!(out, "\n\ndef {a}(*args: Any, **kwargs: Any) -> Callable[[_F], _F]: ...\n");
    }

    out.push_str("\n\n# Built-ins.\n");
    let folds: Vec<&str> = crate::ast::lanes::Fold::ALL.iter().map(|f| f.name()).collect();
    for name in crate::ir::build::names::builtins() {
        if folds.contains(&name.as_str()) || crate::ast::Scalar::from_name(name).is_some() {
            continue;
        }
        let _ = write!(out, "\n\ndef {name}(*args: Any) -> Any: ...\n");
    }

    out.push_str("\n\n# Collectives: `over=ph.ctx.lane` or `over=ph.ctx.thread` folds across the\n# group; with no `over`, `sum` sums a thread's run and `min` and `max` are\n# the binary operators.\n");
    for f in &folds {
        let _ = write!(out, "\n\ndef {f}(*args: Any, over: Any = None, width: int | None = None) -> Any: ...\n");
    }
    out.push_str(
        "\n\ndef shfl(value: Any, *, from_: Any = None, xor: Any = None, down: Any = None, up: Any = None, \
         width: int | None = None) -> Any:\n    \"\"\"`v` from another lane: one of `from_`, `xor`, `down` and `up`.\"\"\"\n",
    );

    out.push_str("\n\n# The standard library.\n");
    for sig in crate::stdlib::builtin().iter().filter(|s| !s.name.starts_with('_')) {
        let doc = doc_comment(&sig.file, &sig.name);
        let _ = write!(out, "\n\ndef {}({}) -> Any:\n", sig.name, sig.params.join(", "));
        if doc.is_empty() {
            out.push_str("    ...\n");
        } else {
            let _ = writeln!(out, "    \"\"\"{}\"\"\"", doc.join("\n    "));
        }
    }
    out
}

/// The `//` lines just before `fn NAME` in library file `file`.
fn doc_comment(file: &str, name: &str) -> Vec<String> {
    let Some(&(_, text)) = crate::stdlib::FILES.iter().find(|(f, _)| *f == file) else {
        return Vec::new();
    };
    let lines: Vec<&str> = text.lines().collect();
    let head = format!("fn {name}(");
    let Some(at) = lines.iter().position(|l| l.starts_with(&head)) else {
        return Vec::new();
    };
    let mut doc: Vec<String> = lines[..at]
        .iter()
        .rev()
        .take_while(|l| l.starts_with("//"))
        .map(|l| l.trim_start_matches("//").trim().replace("\"\"\"", "'''"))
        .collect();
    doc.reverse();
    doc
}

#[cfg(test)]
mod tests {
    /// The committed stubs are what the compiler as built generates.
    #[test]
    fn the_python_stubs_are_current() {
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("..").join(super::PATH);
        let committed = std::fs::read_to_string(&path).unwrap_or_default().replace("\r\n", "\n");
        assert!(
            committed == super::python(),
            "{} is stale: `cargo run -p phobos-lang --features trace --example site -- stubs` rewrites it",
            super::PATH
        );
    }
}
