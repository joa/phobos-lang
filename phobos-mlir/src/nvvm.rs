//! NVIDIA's libNVVM as the LLVM IR to PTX step, where it reads the IR this
//! LLVM writes.
//!
//! The library ships with the CUDA toolkit, not the driver, and is loaded
//! at first use. It takes the IR of a different LLVM per architecture
//! (`nvvmLLVMVersion`): CUDA 13.3 reads LLVM 22 for compute_100 on and LLVM 7
//! typed pointers below, which no current LLVM writes. A chip it cannot
//! read for, or a machine without it, keeps the NVPTX backend.
//! `PHOBOS_NVVM=0` turns it off.
//!
//! The kernel cache keys on neither, so a cache warmed where the library is
//! serves a machine without it. [`current`] tells an entry's compiler from
//! its PTX instead.

use std::ffi::{CStr, CString, c_char, c_int};
use std::path::PathBuf;
use std::sync::{Mutex, OnceLock};

use libloading::Library;

type Program = *mut std::ffi::c_void;

type IrVersion = unsafe extern "C" fn(*mut c_int, *mut c_int, *mut c_int, *mut c_int) -> c_int;
type LlvmVersion = unsafe extern "C" fn(*const c_char, *mut c_int) -> c_int;
type Create = unsafe extern "C" fn(*mut Program) -> c_int;
type Destroy = unsafe extern "C" fn(*mut Program) -> c_int;
type AddModule = unsafe extern "C" fn(Program, *const c_char, usize, *const c_char) -> c_int;
type Compile = unsafe extern "C" fn(Program, c_int, *const *const c_char) -> c_int;
type Size = unsafe extern "C" fn(Program, *mut usize) -> c_int;
type Read = unsafe extern "C" fn(Program, *mut c_char) -> c_int;

struct Nvvm {
    // Keeps the symbols below loaded.
    _lib: Library,
    ir_version: [c_int; 4],
    llvm_version: LlvmVersion,
    create: Create,
    destroy: Destroy,
    add_module: AddModule,
    compile: Compile,
    result_size: Size,
    result: Read,
    log_size: Size,
    log: Read,
    /// What it reads for each architecture asked, `None` for one it rejects.
    readers: Mutex<Vec<(String, Option<c_int>)>>,
}

/// The library's own docs make every call safe from any thread, one program
/// per compile.
unsafe impl Send for Nvvm {}
unsafe impl Sync for Nvvm {}

/// Where a toolkit keeps the library, most specific first.
fn candidates() -> Vec<PathBuf> {
    let (dirs, name): (&[&str], &str) = if cfg!(windows) {
        (&["nvvm/bin/x64", "nvvm/bin"], "nvvm64_40_0.dll")
    } else {
        (&["nvvm/lib64"], "libnvvm.so")
    };
    let mut roots: Vec<PathBuf> = ["CUDA_PATH", "CUDA_HOME"]
        .iter()
        .filter_map(|var| std::env::var_os(var).map(PathBuf::from))
        .collect();
    if !cfg!(windows) {
        roots.push(PathBuf::from("/usr/local/cuda"));
    }
    let mut out: Vec<PathBuf> = roots
        .iter()
        .flat_map(|root| dirs.iter().map(move |dir| root.join(dir).join(name)))
        .collect();
    // Bare, for the loader's own search path, where a distribution's
    // package may keep only the versioned name.
    out.push(PathBuf::from(name));
    if !cfg!(windows) {
        out.push(PathBuf::from("libnvvm.so.4"));
    }
    out
}

/// The first line of the PTX libNVVM writes, which NVPTX's never carries.
const BANNER: &str = "Generated by NVIDIA NVVM Compiler";

impl Nvvm {
    fn open() -> Option<Self> {
        let lib = candidates().into_iter().find_map(|path| unsafe { Library::new(path).ok() })?;
        unsafe {
            let ir_version_fn = *lib.get::<IrVersion>(b"nvvmIRVersion\0").ok()?;
            let mut ir_version = [0; 4];
            if ir_version_fn(&mut ir_version[0], &mut ir_version[1], &mut ir_version[2], &mut ir_version[3]) != 0 {
                return None;
            }
            Some(Nvvm {
                ir_version,
                llvm_version: *lib.get(b"nvvmLLVMVersion\0").ok()?,
                create: *lib.get(b"nvvmCreateProgram\0").ok()?,
                destroy: *lib.get(b"nvvmDestroyProgram\0").ok()?,
                add_module: *lib.get(b"nvvmAddModuleToProgram\0").ok()?,
                compile: *lib.get(b"nvvmCompileProgram\0").ok()?,
                result_size: *lib.get(b"nvvmGetCompiledResultSize\0").ok()?,
                result: *lib.get(b"nvvmGetCompiledResult\0").ok()?,
                log_size: *lib.get(b"nvvmGetProgramLogSize\0").ok()?,
                log: *lib.get(b"nvvmGetProgramLog\0").ok()?,
                _lib: lib,
                readers: Mutex::new(Vec::new()),
            })
        }
    }

    /// The LLVM major the library reads for `arch`, `None` for an
    /// architecture it does not compile for.
    fn reads(&self, arch: &str) -> Option<c_int> {
        let mut readers = self.readers.lock().unwrap_or_else(|e| e.into_inner());
        if let Some((_, major)) = readers.iter().find(|(a, _)| a == arch) {
            return *major;
        }
        let name = CString::new(arch).ok()?;
        let mut major = 0;
        let found = (unsafe { (self.llvm_version)(name.as_ptr(), &mut major) } == 0).then_some(major);
        readers.push((arch.to_string(), found));
        found
    }

    fn compile_module(&self, module: &[u8], arch: &str, extra: &[&str]) -> anyhow::Result<String> {
        let mut options = vec![format!("-arch={arch}")];
        options.extend(extra.iter().map(|o| o.to_string()));
        let options: Vec<CString> = options.into_iter().map(CString::new).collect::<Result<_, _>>()?;
        let pointers: Vec<*const c_char> = options.iter().map(|o| o.as_ptr()).collect();
        unsafe {
            let mut program: Program = std::ptr::null_mut();
            if (self.create)(&mut program) != 0 {
                anyhow::bail!("libNVVM could not create a program");
            }
            let compiled = (|| {
                let added = (self.add_module)(program, module.as_ptr().cast(), module.len(), c"kernel".as_ptr());
                let status = if added != 0 {
                    added
                } else {
                    (self.compile)(program, pointers.len() as c_int, pointers.as_ptr())
                };
                if status != 0 {
                    anyhow::bail!("libNVVM failed for {arch}: {}", self.text(program, self.log_size, self.log));
                }
                Ok(self.text(program, self.result_size, self.result))
            })();
            (self.destroy)(&mut program);
            compiled
        }
    }

    /// One of the program's strings, the log or the PTX.
    unsafe fn text(&self, program: Program, size: Size, read: Read) -> String {
        let mut len = 0;
        if unsafe { size(program, &mut len) } != 0 || len == 0 {
            return String::new();
        }
        let mut buf = vec![0u8; len];
        if unsafe { read(program, buf.as_mut_ptr().cast()) } != 0 {
            return String::new();
        }
        CStr::from_bytes_until_nul(&buf)
            .map(|s| s.to_string_lossy().trim_end().to_owned())
            .unwrap_or_default()
    }
}

fn enabled() -> bool {
    static ON: OnceLock<bool> = OnceLock::new();
    *ON.get_or_init(|| phobos_base::env::flag_on("PHOBOS_NVVM"))
}

fn nvvm() -> Option<&'static Nvvm> {
    static NVVM: OnceLock<Option<Nvvm>> = OnceLock::new();
    NVVM.get_or_init(|| enabled().then(Nvvm::open).flatten()).as_ref()
}

/// The LLVM major this crate links.
fn linked_llvm_major() -> c_int {
    static MAJOR: OnceLock<c_int> = OnceLock::new();
    *MAJOR.get_or_init(|| {
        let (mut major, mut minor, mut patch) = (0, 0, 0);
        unsafe { llvm_sys::core::LLVMGetVersion(&mut major, &mut minor, &mut patch) };
        c_int::try_from(major).unwrap_or(c_int::MAX)
    })
}

/// libNVVM's architecture for an SM chip, `compute_120` for `sm_120`.
fn arch(chip: &str) -> String {
    chip.replacen("sm_", "compute_", 1)
}

/// Whether `chip` compiles through libNVVM here.
pub fn compiles(chip: &str) -> bool {
    // Bitcode reads forward, so a newer reader takes it as well.
    nvvm().and_then(|nvvm| nvvm.reads(&arch(chip))).is_some_and(|major| major >= linked_llvm_major())
}

/// Whether PTX compiled earlier for `chip` came from the compiler this
/// process would use, or one it takes in its place: libNVVM's serves a
/// machine without the library unless `PHOBOS_NVVM=0`, and NVPTX's serves
/// only where libNVVM would not compile the chip. A module libNVVM rejects
/// therefore compiles again in every process that has the library.
pub fn current(chip: &str, ptx: &str) -> bool {
    let by_nvvm = ptx
        .lines()
        .take_while(|line| line.starts_with("//"))
        .any(|line| line.contains(BANNER));
    if by_nvvm { enabled() } else { !compiles(chip) }
}

/// Compiles `module`, which carries the NVPTX triple and data layout, for
/// `chip`. Call only where [`compiles`] holds.
pub(crate) fn compile(module: &inkwell::module::Module<'_>, chip: &str) -> anyhow::Result<String> {
    let nvvm = nvvm().ok_or_else(|| anyhow::anyhow!("libNVVM is not loaded"))?;
    let context = module.get_context();
    let i32_type = context.i32_type();
    let fields: Vec<_> = nvvm
        .ir_version
        .iter()
        .map(|&v| i32_type.const_int(v as u64, false).into())
        .collect();
    module
        .add_global_metadata("nvvmir.version", &context.metadata_node(&fields))
        .map_err(|e| anyhow::anyhow!("nvvmir.version: {e}"))?;
    let bitcode = module.write_bitcode_to_memory();
    // Inkwell's slice carries the buffer's trailing NUL, which bitcode
    // must not.
    let bitcode = bitcode.as_slice().strip_suffix(&[0]).unwrap_or(bitcode.as_slice());
    // Packed f32 pairs stay off, as on the NVPTX path; see ensure_global_init.
    nvvm.compile_module(bitcode, &arch(chip), &["-opt=3", "-Xllc", "-nvptx-no-f32x2"])
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_chip_names_its_virtual_architecture() {
        assert_eq!(arch("sm_120"), "compute_120");
        assert_eq!(arch("sm_90a"), "compute_90a");
    }

    #[test]
    fn the_loader_search_ends_on_bare_names() {
        let last = candidates().pop().unwrap();
        assert_eq!(last.components().count(), 1, "{}", last.display());
    }

    const NVVM_PTX: &str = "//\n// Generated by NVIDIA NVVM Compiler\n//\n\n.version 9.3\n";
    const NVPTX_PTX: &str = "//\n// Generated by LLVM NVPTX Back-End\n//\n\n.version 9.0\n";

    #[test]
    fn libnvvm_ptx_serves_every_machine() {
        for chip in ["sm_75", "sm_120"] {
            assert!(current(chip, NVVM_PTX), "{chip}");
        }
    }

    #[test]
    fn nvptx_ptx_serves_only_where_libnvvm_would_not_compile() {
        for chip in ["sm_75", "sm_120"] {
            assert_eq!(current(chip, NVPTX_PTX), !compiles(chip), "{chip}");
        }
    }

    #[test]
    fn a_chip_libnvvm_takes_compiles_through_it() {
        // Only where a toolkit is installed; the NVPTX path is tested everywhere.
        if !compiles("sm_120") {
            return;
        }
        let context = inkwell::context::Context::create();
        let text = "target datalayout = \"e-p6:32:32-i64:64-i128:128-i256:256-v16:16-v32:32-n16:32:64\"\n\
                    target triple = \"nvptx64-nvidia-cuda\"\n\0";
        let header = inkwell::memory_buffer::MemoryBuffer::create_from_memory_range_copy(text.as_bytes(), "empty");
        let module = context.create_module_from_ir(header).unwrap();
        let ptx = compile(&module, "sm_120").unwrap();
        assert!(ptx.contains(".target sm_120"), "{ptx}");
        assert!(current("sm_120", &ptx));
    }
}
