// The stations of the front page's compiler scene, from source to the GPU. Excerpts come from the
// compiler: a script writes src/data/pipeline/gemm_fp32.json as { "stages": { "<id>": "<excerpt>" } },
// and any stage it covers replaces the placeholder below. Until then each stage shows the placeholder.

export interface PipelineStage {
  id: string
  label: string
  detail: string
  excerpt: string | null
}

export const EXCERPT_PLACEHOLDER = "excerpt generated by the compiler"

const STAGES: Omit<PipelineStage, "excerpt">[] = [
  { id: "source", label: ".ph source", detail: "The kernel as written: examples/gemm_fp32.ph." },
  { id: "ast", label: "AST", detail: "Parsed and checked: tensors, tiles, loops and the ctx fields they use." },
  { id: "graph", label: "graph IR", detail: "Ops and the values between them, before any memory is placed." },
  {
    id: "passes",
    label: "passes",
    detail: "Staging, pipelining, shared-memory placement and barrier elision.",
  },
  { id: "mlir", label: "MLIR", detail: "The gpu dialect, lowered through NVVM to LLVM IR." },
  { id: "ptx", label: "PTX", detail: "Generated by LLVM's NVPTX backend for the chosen chip." },
  { id: "gpu", label: "GPU", detail: "Loaded and launched through CUDA." },
]

interface ExcerptFile {
  stages?: Record<string, string>
}

const generated = import.meta.glob<ExcerptFile>("../../data/pipeline/gemm_fp32.json", {
  eager: true,
  import: "default",
})

export function pipelineStages(): PipelineStage[] {
  const excerpts = Object.values(generated)[0]?.stages ?? {}
  return STAGES.map(stage => ({ ...stage, excerpt: excerpts[stage.id] ?? null }))
}
